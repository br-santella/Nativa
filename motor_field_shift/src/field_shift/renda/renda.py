"""Margin per crop and per rotation. Pure logic (no Streamlit).

margem_cultura = municipal yield (bags/ha, PAM, mean of the last 5 years) × price − cost.
Cover/fallow: − cost. margem_rotacao = summer crop (soybean or summer corn) + second crop + bonus on the following soybean
(bonus_sc × soybean price; includes the summer-corn bonus when it replaces soybean).
margem_incremental = margem_rotacao − municipal summer-soybean margin = (summer margin − soybean margin) + second-crop
margin + bonus. With soybean in summer the first term is zero (soybean is common to those candidates).
Income criterion (score): clip(0.5 + incremental / (2·S), 0, 1), S = max(municipal soybean margin, RENDA_ESCALA_MIN).
References in data/ref/precos_custos.json (generated by field_shift.renda.atualizar).
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd

from field_shift.pam import produtividade as pam_produtividade
from field_shift.pam.produtividade import PAM, serie

ROOT = Path(__file__).resolve().parents[3]
REF = ROOT / "data/ref/precos_custos.json"
# Floor (BRL/ha) of the income criterion's scale S: prevents a very low/negative soybean margin (low price, high
# cost) from stretching the scale and making any small difference saturate the score at 0 or 1.
RENDA_ESCALA_MIN = 1000.0
# cash crop -> price key (yield and cost use the crop's own key)
CULTURAS_VENDA = {"soja": "soja", "milho_2safra": "milho", "trigo": "trigo", "milho_1safra": "milho",
                  "feijao_2safra": "feijao", "sorgo": "sorgo"}
CULTURAS_BASE = ("soja", "milho_2safra", "trigo")  # municipal PAM is required (otherwise, the Western Paraná average for all)
MIN_ANOS_EXTRA = 3  # extra crops (1st-season corn, beans, sorghum): the municipality needs ≥ 3 years of PAM,
ANO_MIN_EXTRA = 2018  # with the latest year ≥ 2018 (sorghum has old, interrupted series); otherwise the Western average is used
ROTULO = {"soja": "Soybean", "milho_2safra": "2nd-season corn", "trigo": "Wheat", "aveia": "Oat (cover)",
          "milheto_crotalaria": "Millet/crotalaria (cover)", "braquiaria_consorcio": "Intercropped brachiaria",
          "pousio": "Fallow (management)", "milho_1safra": "Summer corn (1st season)", "feijao_2safra": "2nd-season beans",
          "sorgo": "Sorghum", "nabo_forrageiro": "Forage radish (cover)", "aveia_nabo": "Oat + radish (cover)"}


@lru_cache(maxsize=1)
def carregar_referencia() -> dict:
    return json.loads(REF.read_text())


@lru_cache(maxsize=1)
def _cods_oeste() -> tuple[str, ...]:
    d = pd.read_parquet(PAM, columns=["cod_ibge"])
    return tuple(sorted(d["cod_ibge"].astype(str).unique()))


def _p20_sc(cod, cult: str) -> float | None:
    s = serie(cod, cult)
    return float(np.percentile(s.iloc[-10:].values, 20) / 60) if len(s) >= 4 else None


def _serve(q: dict, c: str) -> bool:
    """Is the municipal PAM usable for the crop? Base crops: it only has to exist. Extras: ≥ MIN_ANOS_EXTRA years and recent data."""
    return c in q and (c in CULTURAS_BASE or (q[c]["n"] >= MIN_ANOS_EXTRA and int(q[c]["anos"][-4:]) >= ANO_MIN_EXTRA))


def _rend_cultura(q: dict, cod, c: str) -> dict:
    return dict(sc_ha=q[c]["sc_ha"], cv=q[c]["cv"], p20_sc_ha=_p20_sc(cod, c), anos=q[c]["anos"])


def _media_oeste(c: str) -> dict:
    """Mean of the Western Paraná municipalities with PAM for crop `c` (extras: only with ≥ MIN_ANOS_EXTRA years)."""
    v = []
    for cod in _cods_oeste():
        q = pam_produtividade(cod)
        if _serve(q, c):
            v.append((q[c]["sc_ha"], q[c]["cv"], _p20_sc(cod, c), q[c]["anos"]))
    a = np.array([[x if x is not None else np.nan for x in t[:3]] for t in v], dtype=float)
    cv, p20 = (float(np.nanmean(a[:, k])) if not np.all(np.isnan(a[:, k])) else None for k in (1, 2))
    return dict(sc_ha=float(np.nanmean(a[:, 0])), cv=cv, p20_sc_ha=p20, anos=v[-1][3], n_municipios=len(v))


@lru_cache(maxsize=64)
def rendimentos(cod_ibge: str | None) -> dict:
    """{crop: dict(sc_ha, cv, p20_sc_ha, anos)} + keys '_origem' and '_regionais'. Without a municipality (or without PAM for the base crops),
    it uses the mean of the Western Paraná municipalities in PAM ('_origem' says so). The extra crops (1st-season corn, 2nd-season beans,
    sorghum) without enough municipal PAM use the Western Paraná average and are listed in '_regionais'."""
    p = pam_produtividade(cod_ibge) if cod_ibge else {}
    com_base = bool(p) and all(c in p for c in CULTURAS_BASE)
    out, regionais = {}, []
    for c in CULTURAS_VENDA:
        if com_base and _serve(p, c):
            out[c] = _rend_cultura(p, cod_ibge, c)
        else:
            out[c] = _media_oeste(c)
            regionais.append(c)
    out["_regionais"] = regionais if com_base else []  # without base PAM, '_origem' already says everything is the Western average
    out["_origem"] = (f"municipal PAM (IBGE code {cod_ibge})" if com_base else
                      f"average of the {len(_cods_oeste())} Western Paraná municipalities in PAM (field outside the region or without municipal PAM)")
    return out


def _preco(ref, aj, k): return float((aj.get("preco") or {}).get(k, ref["precos"][k]["valor"]))


def _custo(ref, aj, k):
    ov = (aj.get("custo") or {})
    if k in ov:
        return float(ov[k])
    return float(ref["custos"][k][aj.get("linha_custo") or ref.get("linha_custo_padrao", "coe")])


def _rend_efetivo(rend: dict, aj: dict) -> dict:
    """Applies `aj['produtividade']` ({soja|milho_2safra|trigo|milho_1safra|feijao_2safra|sorgo: bags/ha}) over the PAM yield. The bad-year yield
    scales proportionally: own × (p20 / PAM average)."""
    prod = aj.get("produtividade") or {}
    if not prod:
        return rend
    out = dict(rend)
    for k, v in prod.items():
        r = dict(rend[k])
        f = float(v) / r["sc_ha"]
        r["p20_sc_ha"] = None if r["p20_sc_ha"] is None else r["p20_sc_ha"] * f
        r["razao_p20"] = None if rend[k]["p20_sc_ha"] is None else rend[k]["p20_sc_ha"] / rend[k]["sc_ha"]
        r["sc_ha_pam"] = rend[k]["sc_ha"]
        r["sc_ha"], r["usuario"] = float(v), True
        out[k] = r
    return out


def _item(ref, aj, rend, k, rendimento="sc_ha") -> dict:
    c = _custo(ref, aj, k)
    if k in CULTURAS_VENDA:
        pk = CULTURAS_VENDA[k]
        pr = _preco(ref, aj, pk)
        sc = rend[k]["sc_ha"]
        ruim = rend[k]["p20_sc_ha"]
        return dict(chave=k, rotulo=ROTULO[k], sc_ha=sc, preco=pr, custo=c, preco_usuario=pk in (aj.get("preco") or {}),
                    custo_usuario=k in (aj.get("custo") or {}), receita=sc * pr, margem=sc * pr - c,
                    cv=rend[k]["cv"], anos=rend[k]["anos"],
                    margem_ano_ruim=None if ruim is None else ruim * pr - c, sc_ha_ruim=ruim,
                    prod_usuario=bool(rend[k].get("usuario")), razao_p20=rend[k].get("razao_p20"), sc_ha_pam=rend[k].get("sc_ha_pam"))
    return dict(chave=k, rotulo=ROTULO[k], sc_ha=None, preco=None, custo=c, preco_usuario=False,
                custo_usuario=k in (aj.get("custo") or {}), receita=0.0, margem=-c, cv=None, anos=None,
                margem_ano_ruim=-c, sc_ha_ruim=None)


def _item_extra(e: dict) -> dict:
    """Extra cost (machine outsourcing, irrigation): no sale, margin = −cost. `e`: chave, rotulo, custo, detalhe."""
    return dict(chave=e["chave"], rotulo=e["rotulo"], sc_ha=None, preco=None, custo=float(e["custo"]), preco_usuario=False,
                custo_usuario=False, receita=0.0, margem=-float(e["custo"]), cv=None, anos=None,
                margem_ano_ruim=-float(e["custo"]), sc_ha_ruim=None, extra=True, detalhe=e["detalhe"])


def calcular_margens(catalogo: dict, rend: dict, ajustes: dict | None = None, extras: dict | None = None) -> dict:
    """For each candidate: items (soybean, second crop/cover, extras), bonus, total, incremental margin (without soybean) and scale S.
    `ajustes`: {'preco': {soja|milho|trigo: BRL/bag}, 'custo': {key: BRL/ha}, 'linha_custo': 'coe'|'cot'|'ct',
    'produtividade': {soja|milho_2safra|trigo: bags/ha}}. `extras`: {candidate: [dict(chave, rotulo, custo, detalhe)]} (extra costs)."""
    ref, aj = carregar_referencia(), ajustes or {}
    rend = _rend_efetivo(rend, aj)
    extras = extras or {}
    preco_soja = _preco(ref, aj, "soja")
    soja = _item(ref, aj, rend, "soja")
    out = {}
    for nome, c in catalogo.items():
        verao = c.get("item_renda_verao", "soja")  # summer crop: soybean (default) or milho_1safra
        itens = ([soja] if verao == "soja" else [_item(ref, aj, rend, verao)]) + [_item(ref, aj, rend, k) for k in c["renda_itens"]] \
            + [_item_extra(e) for e in extras.get(nome, [])]
        bonus = c["bonus_sc"] * preco_soja
        total = sum(i["margem"] for i in itens) + bonus
        incremental = total - soja["margem"]
        escala = max(soja["margem"], RENDA_ESCALA_MIN)
        ruim = [i["margem_ano_ruim"] for i in itens]
        out[nome] = dict(linha_custo=aj.get("linha_custo") or ref.get("linha_custo_padrao", "coe"), itens=itens, bonus_sc=c["bonus_sc"],
                         bonus_verao_sc=c.get("bonus_verao_sc", 0.0), preco_soja=preco_soja, bonus=bonus, total=total,
                         incremental=incremental, escala_S=escala,
                         total_ano_ruim=None if None in ruim else sum(ruim) + bonus)
    return out


def _fmt(x: float) -> str:
    return f"{x:,.0f}".replace(",", ".")


LINHA_NOME = {"coe": "custo variável (≈COE)", "cot": "COT", "ct": "CT"}


def fonte_custo(i: dict, linha: str) -> str:
    """Short text with the origin of an item's cost (for the table and the card)."""
    if i.get("extra"):
        return i["detalhe"]
    if i["custo_usuario"]:
        return "provided by the user"
    c = carregar_referencia()["custos"][i["chave"]]
    return c["curto"] if c["estimativa"] else f"{c['curto']}, {LINHA_NOME[linha]}"


def fonte_preco(i: dict) -> str:
    if i["preco"] is None:
        return "-"
    if i["preco_usuario"]:
        return "provided by the user"
    p = carregar_referencia()["precos"][CULTURAS_VENDA[i["chave"]]]
    if p.get("estimativa"):
        return "estimate — to be validated: 80% of the SEAB/DERAL-PR corn price"
    return f"SEAB/DERAL-PR, Paraná average {p['periodo'].split(' (')[0]}"
