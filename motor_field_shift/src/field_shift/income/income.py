"""Margin per crop and per rotation. Pure logic (no Streamlit).

crop_margin = municipal yield (bags/ha, PAM: trend of the last 10 years projected to the next season, clipped to the
window min–max; pam.productivity.expected_yield) × price − cost.
Cover/fallow: − cost. rotation_margin = summer crop (soybean or summer corn) + 2nd crop + bonus in the following soybean
(bonus_sc × soybean price; includes the summer-corn bonus in place of soybean).
incremental_margin = rotation_margin − the municipality's summer-soybean margin = (summer margin − soybean margin) + 2nd-crop
margin + bonus. With summer soybean the 1st term is zero (soybean is common to these candidates).
Income criterion (score): 0.5 + 0.5·tanh(incremental / S), S = INCOME_SCALE, the same for every
municipality (engine.income_score; docs/validation.md §7.5).
References in data/ref/precos_custos.json (generated by field_shift.income.update).
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd

from field_shift.i18n import Msg
from field_shift.pam import productivity as pam_yield
from field_shift.pam.productivity import PAM, YIELD_WINDOW_YEARS, series

ROOT = Path(__file__).resolve().parents[3]
REF = ROOT / "data/ref/precos_custos.json"
MESOREGIONS = ROOT / "data/ref/mesorregioes_pr.csv"  # IBGE localidades API: municipality -> mesoregion (399 municipalities of PR)
# Scale S (R$/ha) of the income criterion, the same in every municipality: median soybean margin of the 50 Oeste municipalities
# (BRL 1,111/ha with the reference prices and costs of 11/2026, rounded), i.e. the scale the engine was validated with in the pilot.
# It used to be each municipality's own soybean margin (floor 1,000): where soybean pays more (Centro-Sul, Campos Gerais) the same
# BRL of off-season corn weighed up to 3x less, and the cover crop ranked first against the income evidence (docs/validation.md §7.5).
INCOME_SCALE = 1110.0
# sold crop -> price key (yield and cost use the crop's own key)
CASH_CROPS = {"soja": "soja", "milho_2safra": "milho", "trigo": "trigo", "milho_1safra": "milho",
                  "feijao_2safra": "feijao", "sorgo": "sorgo"}
BASE_CROPS = ("soja", "milho_2safra", "trigo")  # the municipality PAM is required (otherwise the mesoregion mean for all of them)
MIN_YEARS_EXTRA = 3  # extra crops (1st-season corn, beans, sorghum): the municipality needs ≥ 3 years of PAM,
MIN_YEAR_EXTRA = 2018  # with the last year ≥ 2018 (sorghum has old, interrupted series); otherwise the mesoregion mean is used
LABEL = {"soja": "Soja", "milho_2safra": "Milho 2ª safra", "trigo": "Trigo", "aveia": "Aveia (cobertura)",
          "milheto_crotalaria": "Milheto/crotalária (cobertura)", "braquiaria_consorcio": "Braquiária em consórcio",
          "pousio": "Pousio (manejo)", "milho_1safra": "Milho verão (1ª safra)", "feijao_2safra": "Feijão 2ª safra",
          "sorgo": "Sorgo", "nabo_forrageiro": "Nabo forrageiro (cobertura)", "aveia_nabo": "Aveia + nabo (cobertura)"}


@lru_cache(maxsize=1)
def load_reference() -> dict:
    return json.loads(REF.read_text())


@lru_cache(maxsize=1)
def _mesoregions() -> pd.DataFrame:
    return pd.read_csv(MESOREGIONS, dtype={"cod_ibge": str})


def region_label(meso: str | None) -> str:
    """Short display name of an IBGE mesoregion ('Oeste Paranaense' -> 'Oeste do PR'); None -> 'Paraná'."""
    if not meso:
        return "Paraná"
    return meso.replace(" Paranaense", " do PR") if meso.endswith(" Paranaense") else meso


def mesoregion(cod_ibge: str | None) -> str | None:
    """IBGE mesoregion of a Paraná municipality (None if unknown)."""
    if cod_ibge is None:
        return None
    m = _mesoregions()
    row = m[m["cod_ibge"] == str(cod_ibge)]
    return None if row.empty else str(row["mesorregiao"].iloc[0])


@lru_cache(maxsize=16)
def _region_codes(meso: str | None) -> tuple[str, ...]:
    """IBGE codes with PAM of the mesoregion (the reference set of the regional mean); None = all of Paraná.
    For the Oeste this is the same 50-municipality set the engine was validated on."""
    m = _mesoregions()
    cods = set(m["cod_ibge"] if meso is None else m.loc[m["mesorregiao"] == meso, "cod_ibge"])
    d = pd.read_parquet(PAM, columns=["cod_ibge"])
    return tuple(sorted(cods & set(d["cod_ibge"].astype(str).unique())))


def _p20_sc(cod, cult: str) -> float | None:
    s = series(cod, cult)
    return float(np.percentile(s.iloc[-YIELD_WINDOW_YEARS:].values, 20) / 60) if len(s) >= 4 else None


def _serve(q: dict, c: str) -> bool:
    """Is the municipality PAM good enough for the crop? Base crops: it only has to exist. Extras: ≥ MIN_YEARS_EXTRA years and recent data."""
    return c in q and (c in BASE_CROPS or (q[c]["n"] >= MIN_YEARS_EXTRA and int(q[c]["anos"][-4:]) >= MIN_YEAR_EXTRA))


def _crop_yield(q: dict, cod, c: str) -> dict:
    p20 = _p20_sc(cod, c)
    p20 = None if p20 is None else min(p20, q[c]["sc_ha"])  # the bad year never above the expected yield
    return dict(sc_ha=q[c]["sc_ha"], cv=q[c]["cv"], p20_sc_ha=p20, anos=q[c]["anos"], media_sc_ha=q[c]["media_sc_ha"],
                metodo=q[c]["metodo"])


def _region_mean(c: str, meso: str | None) -> dict:
    """Mean of the mesoregion municipalities with PAM for crop `c` (extras: only those with ≥ MIN_YEARS_EXTRA years). Falls back
    to all of Paraná when no municipality of the mesoregion serves the crop."""
    v = []
    for cod in _region_codes(meso):
        q = pam_yield(cod)
        if _serve(q, c):
            p20 = _p20_sc(cod, c)
            v.append((q[c]["sc_ha"], q[c]["cv"], None if p20 is None else min(p20, q[c]["sc_ha"]), q[c]["anos"],
                      q[c]["media_sc_ha"]))
    if not v and meso is not None:
        return _region_mean(c, None)
    a = np.array([[x if x is not None else np.nan for x in t[:3]] for t in v], dtype=float)
    cv, p20 = (float(np.nanmean(a[:, k])) if not np.all(np.isnan(a[:, k])) else None for k in (1, 2))
    return dict(sc_ha=float(np.nanmean(a[:, 0])), cv=cv, p20_sc_ha=p20, anos=v[-1][3], n_municipios=len(v),
                media_sc_ha=float(np.mean([t[4] for t in v])), metodo="tendência", regiao=region_label(meso))


@lru_cache(maxsize=512)
def yields(cod_ibge: str | None) -> dict:
    """{crop: dict(sc_ha, cv, p20_sc_ha, anos)} + keys '_origem', '_regionais' and '_regiao'. Without PAM for the base crops in the
    municipality, uses the mean of the municipalities of its IBGE mesoregion in the PAM ('_origem' warns; without a municipality,
    all of Paraná). Extra crops (1st-season corn, 2nd-season beans, sorghum) without enough PAM in the municipality use the
    mesoregion mean, listed in '_regionais'. For the Oeste this is the 50-municipality mean the engine was validated on."""
    meso = mesoregion(cod_ibge)
    region = region_label(meso)
    p = pam_yield(cod_ibge) if cod_ibge else {}
    com_base = bool(p) and all(c in p for c in BASE_CROPS)
    out, regional = {}, []
    for c in CASH_CROPS:
        if com_base and _serve(p, c):
            out[c] = _crop_yield(p, cod_ibge, c)
        else:
            out[c] = _region_mean(c, meso)
            regional.append(c)
    out["_regionais"] = regional if com_base else []  # no base PAM: '_origem' already warns that everything is the regional mean
    out["_regiao"] = region
    out["_origem"] = (f"PAM do município (cód. IBGE {cod_ibge})" if com_base else
                      Msg("média dos {0} municípios da mesorregião {1} na PAM (o município não tem PAM de soja, milho 2ª safra e trigo)",
                          str(out["soja"]["n_municipios"]), out["soja"]["regiao"]) if meso is not None else
                      Msg("média dos {0} municípios do Paraná na PAM (sem município)", str(out["soja"]["n_municipios"])))
    return out


def _price(ref, aj, k): return float((aj.get("preco") or {}).get(k, ref["prices"][k]["value"]))


def _cost(ref, aj, k):
    ov = (aj.get("custo") or {})
    if k in ov:
        return float(ov[k])
    return float(ref["costs"][k][aj.get("linha_custo") or ref.get("default_cost_line", "coe")])


def _effective_yield(rend: dict, aj: dict) -> dict:
    """Apply `aj['produtividade']` ({soja|milho_2safra|trigo|milho_1safra|feijao_2safra|sorgo: bags/ha}) over the PAM yield. The bad-year
    yield scales proportionally: own × (p20 / PAM mean)."""
    prod = aj.get("produtividade") or {}
    if not prod:
        return rend
    out = dict(rend)
    for k, v in prod.items():
        r = dict(rend[k])
        f = float(v) / r["sc_ha"]
        r["p20_sc_ha"] = None if r["p20_sc_ha"] is None else r["p20_sc_ha"] * f
        r["razao_p20"] = None if rend[k]["p20_sc_ha"] is None else rend[k]["p20_sc_ha"] / rend[k]["sc_ha"]
        r["sc_ha_pam"] = rend[k]["sc_ha"]
        r["sc_ha"], r["usuario"] = float(v), True
        out[k] = r
    return out


def yield_cost_factor(ref: dict, aj: dict, k: str, sc_ha: float) -> float | None:
    """Ratio local yield / CONAB reference yield, for crops whose CONAB cost sheet has a yield-driven split.

    None when the crop has no split or the farmer typed their own cost (their number is used as given).
    """
    scale = ref["costs"][k].get("yield_scale")
    if scale is None or k in (aj.get("custo") or {}):
        return None
    return sc_ha / scale["reference_sc_ha"]


def _scaled_cost(ref: dict, k: str, cost: float, factor: float | None) -> float:
    """Remove the yield-driven share of `cost` that the local yield does not justify (applies to every cost line:
    the fixed lines `cot`/`ct` only add costs that do not depend on yield)."""
    if factor is None:
        return cost
    return cost - ref["costs"][k]["yield_scale"]["proportional_r_ha"] * (1 - factor)


def _item(ref, aj, rend, k, yield_="sc_ha") -> dict:
    c = _cost(ref, aj, k)
    factor = None
    if k in CASH_CROPS:
        factor = yield_cost_factor(ref, aj, k, rend[k]["sc_ha"])
        c_base = c
        c = _scaled_cost(ref, k, c, factor)  # a bad year keeps the same cost: inputs are already spent
        pk = CASH_CROPS[k]
        pr = _price(ref, aj, pk)
        sc = rend[k]["sc_ha"]
        bad = rend[k]["p20_sc_ha"]
        return dict(chave=k, rotulo=LABEL[k], sc_ha=sc, preco=pr, custo=c, custo_base=c_base, fator_escala_custo=factor,
                    preco_usuario=pk in (aj.get("preco") or {}),
                    custo_usuario=k in (aj.get("custo") or {}), receita=sc * pr, margem=sc * pr - c,
                    cv=rend[k]["cv"], anos=rend[k]["anos"],
                    margem_ano_ruim=None if bad is None else bad * pr - c, sc_ha_ruim=bad,
                    prod_usuario=bool(rend[k].get("usuario")), razao_p20=rend[k].get("razao_p20"), sc_ha_pam=rend[k].get("sc_ha_pam"),
                    sc_ha_media=rend[k].get("media_sc_ha"), metodo_rend=rend[k].get("metodo"))
    return dict(chave=k, rotulo=LABEL[k], sc_ha=None, preco=None, custo=c, preco_usuario=False,
                custo_usuario=k in (aj.get("custo") or {}), receita=0.0, margem=-c, cv=None, anos=None,
                margem_ano_ruim=-c, sc_ha_ruim=None)


def _item_extra(e: dict) -> dict:
    """Extra cost (machine outsourcing, irrigation): no sale, margin = −cost. `e`: chave, rotulo, custo, detalhe."""
    return dict(chave=e["chave"], rotulo=e["rotulo"], sc_ha=None, preco=None, custo=float(e["custo"]), preco_usuario=False,
                custo_usuario=False, receita=0.0, margem=-float(e["custo"]), cv=None, anos=None,
                margem_ano_ruim=-float(e["custo"]), sc_ha_ruim=None, extra=True, detalhe=e["detalhe"])


def compute_margins(catalog: dict, rend: dict, adjustments: dict | None = None, extras: dict | None = None) -> dict:
    """For each candidate: items (soybean, 2nd crop/cover, extras), bonus, total, incremental margin (without soybean) and S scale.
    `adjustments`: {'preco': {soja|milho|trigo: R$/bag}, 'custo': {key: R$/ha}, 'linha_custo': 'coe'|'cot'|'ct',
    'produtividade': {soja|milho_2safra|trigo: bags/ha}}. `extras`: {candidate: [dict(chave, rotulo, custo, detalhe)]} (extra costs)."""
    ref, aj = load_reference(), adjustments or {}
    rend = _effective_yield(rend, aj)
    extras = extras or {}
    soy_price = _price(ref, aj, "soja")
    soy = _item(ref, aj, rend, "soja")
    out = {}
    for nome, c in catalog.items():
        summer = c.get("item_renda_verao", "soja")  # summer crop: soybean (default) or milho_1safra
        items = ([soy] if summer == "soja" else [_item(ref, aj, rend, summer)]) + [_item(ref, aj, rend, k) for k in c["renda_itens"]] \
            + [_item_extra(e) for e in extras.get(nome, [])]
        bonus = c["bonus_sc"] * soy_price
        total = sum(i["margem"] for i in items) + bonus
        incremental = total - soy["margem"]
        scale = INCOME_SCALE
        bad = [i["margem_ano_ruim"] for i in items]
        out[nome] = dict(linha_custo=aj.get("linha_custo") or ref.get("default_cost_line", "coe"), itens=items, bonus_sc=c["bonus_sc"],
                         bonus_verao_sc=c.get("bonus_verao_sc", 0.0), preco_soja=soy_price, bonus=bonus, total=total,
                         incremental=incremental, escala_S=scale,
                         total_ano_ruim=None if None in bad else sum(bad) + bonus)
    return out


def _fmt(x: float) -> str:
    return f"{x:,.0f}".replace(",", ".")


COST_LINE_NAME = {"coe": "custo variável (≈COE)", "cot": "COT", "ct": "CT"}


def cost_source(i: dict, line: str) -> str:
    """Short text of the cost origin of an item (for the table and the card)."""
    if i.get("extra"):
        return i["detalhe"]
    if i["custo_usuario"]:
        return "informado pelo usuário"
    c = load_reference()["costs"][i["chave"]]
    text = c["short"] if c["estimate"] else Msg("{0}, {1}", c["short"], COST_LINE_NAME[line])
    f = i.get("fator_escala_custo")
    if f is not None:
        ref_sc = c["yield_scale"]["reference_sc_ha"]
        text = Msg("{0}; fertilizantes, transporte, armazenagem e CESSR ajustados à produtividade local "
                   "({1} sc/ha contra {2} sc/ha da referência CONAB) — estimativa, validar", text, f"{i['sc_ha']:.0f}", f"{ref_sc:.0f}")
    return text


def price_source(i: dict) -> str:
    if i["preco"] is None:
        return "-"
    if i["preco_usuario"]:
        return "informado pelo usuário"
    p = load_reference()["prices"][CASH_CROPS[i["chave"]]]
    if p.get("estimate"):
        return Msg("estimativa — validar: {0} do preço do milho SEAB/DERAL-PR (razão dos preços mínimos CONAB, não de mercado)",
                   f"{p.get('ratio_to_corn', 0.8):.0%}")
    return Msg("SEAB/DERAL-PR, média PR {0}", p["period"].split(" (")[0])
