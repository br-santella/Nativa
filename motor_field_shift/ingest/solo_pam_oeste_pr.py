"""Regional ingestion: SoilGrids (soil) and IBGE PAM (municipal yield) for Western Paraná.

Subcommands (idempotent: skip what already exists; --force redoes it):
  soilgrids  clips the Western Paraná bbox (+margin) from the ISRIC VRTs, reprojects to EPSG:4326
             (~0.0025° ≈ 275 m) and saves 1 GeoTIFF per property in data/raw/soilgrids_oeste_pr/
             (4 bands = 0-5, 5-15, 15-30, 30-60 cm), already in PHYSICAL UNITS (see ESCALAS).
  pam        downloads SIDRA (table 1612: soybean, total corn, wheat, oat; table 839: 1st- and 2nd-season corn)
             for the 50 municipalities -> data/raw/ibge/pam_oeste_pr.parquet (long format).
  all        both.

Usage: uv run python ingest/solo_pam_oeste_pr.py {soilgrids|pam|all} [--force] [--regiao oeste_pr|pr]
  --regiao pr: whole of Paraná (399 municipalities; reads regiao/pr.geojson and municipios_pr.geojson, generated by
  ingest/mapbiomas_relevo_oeste_pr.py --regiao pr) -> data/raw/soilgrids_pr/ and data/raw/ibge/pam_pr.parquet.
"""
import argparse
import time
from pathlib import Path

import geopandas as gpd
import numpy as np
import pandas as pd
import rasterio
import requests
from rasterio.transform import from_origin
from rasterio.warp import Resampling, reproject, transform_bounds
from rasterio.windows import from_bounds

ROOT = Path(__file__).resolve().parents[1]
REG = ROOT / "data/raw/regiao"
SUF = "oeste_pr"
SG = ROOT / "data/raw/soilgrids_oeste_pr"
PAM = ROOT / "data/raw/ibge/pam_oeste_pr.parquet"
VRT = "/vsicurl/https://files.isric.org/soilgrids/latest/data/{p}/{p}_{d}_mean.vrt"
PROFS = ["0-5cm", "5-15cm", "15-30cm", "30-60cm"]
MARGEM = 0.1
RES = 0.0025  # degrees

# SoilGrids 2.0 scale factors (mapped integer value / factor = physical unit).
# physical unit saved: clay/sand/silt in % (g/100 g; mapped in g/kg -> /10);
# soc in g/kg (mapped in dg/kg -> /10); phh2o in pH (mapped ×10 -> /10);
# bdod in g/cm³ (mapped in cg/cm³ -> /100).
# wv0033/wv1500 do NOT exist on the server (latest/data only has bdod, cec, cfvo, clay, nitrogen, ocd, ocs, phh2o, sand, silt, soc, wrb),
# so the AWC comes from a pedotransfer (Saxton & Rawls) in the field_shift.solo module.
ESCALAS = {"clay": 10.0, "sand": 10.0, "silt": 10.0, "soc": 10.0, "phh2o": 10.0, "bdod": 100.0}


def configurar(regiao):
    global SUF, SG, PAM
    SUF = regiao
    SG = ROOT / f"data/raw/soilgrids_{regiao}"
    PAM = ROOT / f"data/raw/ibge/pam_{regiao}.parquet"


def bbox():
    b = gpd.read_file(REG / f"{SUF}.geojson").total_bounds
    return b[0] - MARGEM, b[1] - MARGEM, b[2] + MARGEM, b[3] + MARGEM


def soilgrids(force=False, props=None):
    SG.mkdir(parents=True, exist_ok=True)
    w, s, e, n = bbox()
    ncol, nrow = int(round((e - w) / RES)), int(round((n - s) / RES))
    dst_tr = from_origin(w, n, RES, RES)
    for prop, fator in ESCALAS.items():
        if props and prop not in props:
            continue
        out = SG / f"{prop}.tif"
        if out.exists() and not force:
            print("already exists:", out.name)
            continue
        bandas = []
        for d in PROFS:
            t0 = time.time()
            for tent in range(4):
                try:
                    with rasterio.open(VRT.format(p=prop, d=d)) as src:
                        bb = transform_bounds("EPSG:4326", src.crs, w, s, e, n, densify_pts=50)
                        win = from_bounds(*bb, transform=src.transform).round_offsets().round_lengths()
                        dados = src.read(1, window=win).astype("float32")
                        tr = src.window_transform(win)
                        nod = src.nodata
                        crs = src.crs
                    break
                except Exception as ex:  # unstable network
                    print("  retry", prop, d, type(ex).__name__)
                    time.sleep(5)
            else:
                raise RuntimeError(f"failed {prop} {d}")
            dados[dados == nod] = np.nan
            dst = np.full((nrow, ncol), np.nan, "float32")
            reproject(dados, dst, src_transform=tr, src_crs=crs, dst_transform=dst_tr, dst_crs="EPSG:4326",
                      src_nodata=np.nan, dst_nodata=np.nan, resampling=Resampling.bilinear)
            bandas.append(dst / fator)
            print(f"  {prop} {d}: {time.time() - t0:.0f}s, mean {np.nanmean(dst / fator):.2f}")
        with rasterio.open(out, "w", driver="GTiff", height=nrow, width=ncol, count=len(PROFS), dtype="float32",
                           crs="EPSG:4326", transform=dst_tr, nodata=np.nan, compress="deflate",
                           predictor=3, tiled=True) as dst_f:
            for i, b in enumerate(bandas, 1):
                dst_f.write(b, i)
                dst_f.set_band_description(i, f"{prop} {PROFS[i - 1]}")
        print("salvo", out, out.stat().st_size // 1024, "KB")


# ------------------------------------------------------------------------------- PAM
SIDRA = "https://apisidra.ibge.gov.br/values"
VARS = {"109": "area_plantada_ha", "216": "area_colhida_ha", "214": "producao_t", "112": "rendimento_kg_ha"}
VAR_VALOR = {"215": "valor_mil_reais"}
# table 1612, classification 81 (product): 2713 soybean, 2711 corn (grain, total), 2716 wheat, 2693 oat
PROD_1612 = {"2713": "soja", "2711": "milho_total", "2716": "trigo", "2693": "aveia"}
# table 839, classification 81: 114253 1st-season corn, 114254 2nd-season corn
PROD_839 = {"114253": "milho_1safra", "114254": "milho_2safra"}


def _sidra(tabela, vars_, prods, munis):
    url = (f"{SIDRA}/t/{tabela}/n6/{','.join(munis)}/v/{','.join(vars_)}/p/all/c81/{','.join(prods)}")
    for tent in range(4):
        try:
            r = requests.get(url, timeout=180)
            r.raise_for_status()
            return r.json()[1:]  # row 0 = header
        except Exception as ex:
            print("  retry SIDRA", type(ex).__name__)
            time.sleep(5)
    raise RuntimeError("SIDRA failed")


def pam(force=False):
    if PAM.exists() and not force:
        print("already exists:", PAM)
        return
    PAM.parent.mkdir(parents=True, exist_ok=True)
    munis = [str(int(c)) for c in gpd.read_file(REG / f"municipios_{SUF}.geojson")["cod_ibge"]]
    linhas = []
    for tabela, vars_, prods in [("1612", {**VARS, **VAR_VALOR}, PROD_1612), ("839", VARS, PROD_839)]:
        for i in range(0, len(munis), 10):
            lote = munis[i:i + 10]
            for j in _sidra(tabela, list(vars_), list(prods), lote):
                linhas.append(dict(tabela=tabela, cod_ibge=j["D1C"], ano=int(j["D3C"]), variavel=vars_[j["D2C"]],
                                   cultura=prods[j["D4C"]], valor_bruto=j["V"]))
            print(f"  table {tabela}: municipalities {i + 1}-{i + len(lote)}")
    df = pd.DataFrame(linhas)
    # "-" (absolute zero), "..." (not applicable), "X" (withheld for confidentiality), ".." and "" -> NaN
    df["valor"] = pd.to_numeric(df["valor_bruto"].replace({"-": None, "...": None, "..": None, "X": None, "": None}),
                                errors="coerce")
    df = df.drop(columns="valor_bruto")
    df.to_parquet(PAM, index=False)
    print("saved", PAM, len(df), "rows,", df.cod_ibge.nunique(), "municipalities, years", df.ano.min(), "-", df.ano.max(),
          f"{PAM.stat().st_size // 1024} KB")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["soilgrids", "pam", "all"])
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--regiao", choices=["oeste_pr", "pr"], default="oeste_pr")
    ap.add_argument("--props", nargs="*", help="only these SoilGrids properties (allows running in parallel)")
    a = ap.parse_args()
    configurar(a.regiao)
    if a.cmd in ("soilgrids", "all"):
        soilgrids(a.force, a.props)
    if a.cmd in ("pam", "all"):
        pam(a.force)
